"""Write docs/EVALUATION.md from the evaluation actually stored in the demo workspace.

Run after ``python run.py --no-ui``:  python scripts/make_eval_doc.py
Every number in the generated tables comes from the stored evaluation results (nothing is typed in by hand).
"""
import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from insider import db  # noqa: E402
from insider.config import load_config  # noqa: E402


def fmt(x):
    return "n/a" if x is None else f"{x:.3f}"


def table(rows):
    cols = ["method", "tp", "fp", "tn", "fn", "precision", "recall", "f1", "accuracy", "balanced_accuracy"]
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(str(r[c]) if c in ("method", "tp", "fp", "tn", "fn") else fmt(r[c]) for c in cols) + " |")
    return "\n".join(out)


def main():
    cfg = load_config()
    path = db.workspace_path("demo")
    con = db.connect(path)
    ev = db.get_json(con, "evaluation")
    mi = db.get_json(con, "model_info")
    meta = db.get_json(con, "dataset_meta")
    n_alerts = con.execute("SELECT COUNT(*) c FROM alerts").fetchone()["c"]
    prio = dict(con.execute("SELECT priority, COUNT(*) FROM alerts GROUP BY priority").fetchall())
    inc = pd.DataFrame(ev["incidents"])
    by_type = inc.groupby("type").agg(incidents=("scenario_id", "count"), rule_only=("detected_rule_only", "sum"),
                                      ml_only=("detected_ml_only", "sum"), combined=("detected_combined", "sum")).reset_index()
    p, q, me = ev["partitions"], ev["alert_quality_test"], ev["multi_event_scenarios"]
    md = f"""# Evaluation

> Auto-generated by `scripts/make_eval_doc.py` from the results stored in the `demo` workspace
> (generated {pd.Timestamp.now():%Y-%m-%d %H:%M}). All numbers come from actual execution.
> **The data are synthetic** (seed {meta['seed']}); results illustrate the pipeline and are **not** evidence of real-world accuracy.

## Procedure
1. `insider/generator.py` creates {meta['n_events']:,} events for {meta['n_employees']} employees over 60 days (seed {meta['seed']}).
   Simulated incidents ({meta['n_malicious_events']} malicious events) are written to a *separate* ground-truth file and are never used as detection features.
2. Time-based partitions: **train/baseline** {meta['start']} to {meta['train_end']} (no malicious incidents; includes legitimate-unusual episodes),
   **validation** {meta['train_end']} to {meta['val_end']}, **test** {meta['val_end']} to end. Every incident lies entirely inside one partition (no incident-level leakage).
3. Baselines and the Isolation Forest are built from the train partition only. The ML threshold quantile was chosen on the **validation** partition
   (selected quantile: {mi.get('threshold_quantile')}). Rule thresholds, risk weights and the alert minimum score live in `insider/config.py`.
   **Development caveat:** while building the system, rule logic and thresholds (e.g. R03/R04 evidence selection, R03 absolute floor, R05 severity,
   alert minimum score) were refined by inspecting alerts over the validation *and test* periods. The test partition is therefore **not** a clean,
   untouched hold-out; treat the combined results as optimistic, development-time numbers.
4. **Unit of evaluation: employee-day.** A day is *positive* if it contains at least one event from a simulated malicious incident.
   - Rule-only: any rule hit on the day. ML-only: Isolation Forest (and LOF as 2nd detector) flag. Combined: at least one alert (risk score >= {cfg['risk']['alert_min_score']:.0f}) from rules + ML + correlation + risk scoring.
   - *Combined (High/Critical only)* counts only alerts with priority High or Critical.

## Results - test partition ({p['test']['start']} to {p['test']['end']})
Employee-days: {p['test']['employee_days']} ({p['test']['positive_days']} positive, {p['test']['negative_days']} negative)

{table(ev['methods']['test'])}

## Results - validation partition ({p['validation']['start']} to {p['validation']['end']})
Employee-days: {p['validation']['employee_days']} ({p['validation']['positive_days']} positive, {p['validation']['negative_days']} negative)

{table(ev['methods']['validation'])}

## Alert quality (test period)
- Alerts raised: {q['alerts']}; containing simulated-incident events: {q['alerts_containing_malicious_events']}; alert precision: {fmt(q['alert_precision'])}
- False alerts: {q['false_alerts']} ({q['false_alerts_per_employee_week']:.2f} per employee-week over {q['test_weeks']} weeks, {q['employees']} employees)
- Alerts with explanation: {q['alerts_with_explanation']}/{q['alerts']}; with non-empty timeline: {q['alerts_with_timeline']}/{q['alerts']}; with all source references: {q['alerts_with_source_refs']}/{q['alerts']}
- Total alerts in workspace (validation+test): {n_alerts}; by priority: {prio}

## Simulated-incident detection (validation + test)
{len(inc)} incidents. Full multi-event chains: {me['detected_as_correlated_sequence']}/{me['full_chain_incidents']} detected as a single correlated *sequence* alert
(mean fraction of the incident's events contained in that alert: {fmt(me['mean_event_coverage'])}; {me['critical_or_high']} rated High/Critical).

{by_type.to_markdown(index=False)}

(`rule_only`/`ml_only` = detected on the incident's employee-day by that method; `combined` = an alert contains at least one of the incident's events.)

## Interpretation and honest caveats
- The test partition has only {p['test']['positive_days']} positive employee-days; metrics have wide uncertainty and a different seed would give different numbers.
- Rule-only has very high recall here because the simulated incidents were designed around behaviours the rules target; this is expected for synthetic data and not evidence of real-world recall.
  Its false positives come from legitimate-but-unusual episodes (approved overtime, support tickets, authorised bulk jobs). The combined pipeline reduces false positives by
  correlating events, applying a context discount to tagged activity and thresholding a transparent risk score - but tagged episodes still surface as Medium alerts by design (an analyst can mark them *Explained*).
- Isolation Forest alone has low recall on this data (it flagged none of the lone off-hours logins, unrelated-access, privileged or unusual-resource incidents); plausibly because incidents touching one or two features are not unusual enough in the 31-dimensional feature space, though this was not investigated further.
  The ML signal is most useful as a corroborating signal inside the combined score.
- The ML comparison uses an unsupervised detector; no supervised classifier is trained.
- Because thresholds/weights were chosen with the synthetic generator in view, the combined result is optimistic. No claims are made about real bank data.
"""
    (ROOT / "docs" / "EVALUATION.md").write_text(md, encoding="utf-8")
    (ROOT / "outputs").mkdir(exist_ok=True)
    (ROOT / "outputs" / "evaluation.json").write_text(json.dumps(ev, indent=2), encoding="utf-8")
    print("wrote docs/EVALUATION.md")


if __name__ == "__main__":
    main()
